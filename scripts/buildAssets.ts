import { readFileSync, writeFileSync } from "node:fs";

/**
 * Convex deploys code, not loose files. The pdf fonts and the e-mail photo are
 * embedded as base64 modules; rerun this after changing anything in assets/.
 *
 * Fonts: Schibsted Grotesk, Carlito and Reenie Beanie (SIL Open Font License),
 * downloaded from Google Fonts (Reenie Beanie from github.com/google/fonts:
 * the Google Fonts API build of it crashes fontkit). Photo: public/anton.webp as a 480 px JPEG.
 */
const fonts = {
  uiRegular: "SchibstedGrotesk-Regular.ttf",
  uiSemiBold: "SchibstedGrotesk-SemiBold.ttf",
  uiBold: "SchibstedGrotesk-Bold.ttf",
  docRegular: "Carlito-Regular.ttf",
  docItalic: "Carlito-Italic.ttf",
  hand: "ReenieBeanie-Regular.ttf",
};
const header = "// Generated by `npm run assets:build`. Do not edit.\n";
const base64 = (path: string) => readFileSync(path).toString("base64");

writeFileSync(
  "shared/report/fonts.generated.ts",
  header +
    Object.entries(fonts)
      .map(([name, file]) => `export const ${name} = "${base64(`assets/fonts/${file}`)}";`)
      .join("\n") +
    "\n",
);
writeFileSync(
  "shared/email/photo.generated.ts",
  `${header}export const antonPhotoJpeg = "${base64("assets/email/anton-charlotte.jpg")}";\n`,
);
console.log("Wrote shared/report/fonts.generated.ts and shared/email/photo.generated.ts");
